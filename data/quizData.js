// Get localized quiz sets
export const getLocalizedQuizSets = (lang = 'sq') => {
  if (lang === 'sq') return quizSets;

  const translations = quizzesTranslationsMap[lang];
  if (!translations) return quizSets;

  return quizSets.map(quizSet => {
    const t = translations[quizSet.id];
    if (!t) return quizSet;

    return {
      ...quizSet,
      title: t.title || quizSet.title,
      category: t.category || quizSet.category,
      questions: quizSet.questions.map((q, i) => {
        const tq = t.questions?.[i];
        if (!tq) return q;
        return {
          ...q,
          question: tq.question || q.question,
          options: tq.options || q.options,
          explanation: tq.explanation || q.explanation,
        };
      }),
    };
  });
};

